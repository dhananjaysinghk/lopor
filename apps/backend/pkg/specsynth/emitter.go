package specsynth

import (
	"fmt"
	"strings"
)

// FormatOpenAPI30 renders a complete OpenAPI 3.0.3 specification in YAML.
func FormatOpenAPI30(title, version string, endpoints []EndpointSpec, models []ModelDefinition) string {
	var b strings.Builder

	if version == "" {
		version = "1.0.0"
	}

	b.WriteString("openapi: 3.0.3\n")
	b.WriteString("info:\n")
	b.WriteString(fmt.Sprintf("  title: \"%s\"\n", title))
	b.WriteString(fmt.Sprintf("  version: \"%s\"\n", version))
	b.WriteString("  description: \"Synthesized enterprise API specification generated by Lopor SpecSynth Engine.\"\n")
	b.WriteString("paths:\n")

	// Group endpoints by path
	pathMap := make(map[string][]EndpointSpec)
	for _, ep := range endpoints {
		pathMap[ep.Path] = append(pathMap[ep.Path], ep)
	}

	for path, eps := range pathMap {
		b.WriteString(fmt.Sprintf("  %s:\n", path))
		for _, ep := range eps {
			method := strings.ToLower(ep.Method)
			b.WriteString(fmt.Sprintf("    %s:\n", method))
			b.WriteString(fmt.Sprintf("      summary: \"%s\"\n", ep.Summary))

			if len(ep.PathParams) > 0 {
				b.WriteString("      parameters:\n")
				for paramName, paramType := range ep.PathParams {
					b.WriteString(fmt.Sprintf("        - name: \"%s\"\n", paramName))
					b.WriteString("          in: path\n")
					b.WriteString("          required: true\n")
					b.WriteString("          schema:\n")
					b.WriteString(fmt.Sprintf("            type: %s\n", paramType))
				}
			}

			b.WriteString("      responses:\n")
			b.WriteString(fmt.Sprintf("        '%d':\n", ep.StatusCode))
			b.WriteString("          description: \"Successful operation\"\n")
		}
	}

	if len(models) > 0 {
		b.WriteString("components:\n")
		b.WriteString("  schemas:\n")
		for _, m := range models {
			b.WriteString(fmt.Sprintf("    %s:\n", m.Name))
			b.WriteString("      type: object\n")
			b.WriteString("      properties:\n")
			for fn, ft := range m.Fields {
				b.WriteString(fmt.Sprintf("        %s:\n", fn))
				b.WriteString(fmt.Sprintf("          type: %s\n", ft))
			}
			if len(m.Required) > 0 {
				b.WriteString("      required:\n")
				for _, r := range m.Required {
					b.WriteString(fmt.Sprintf("        - %s\n", r))
				}
			}
		}
	}

	return b.String()
}

// FormatGraphQLSDL renders a GraphQL Schema Definition Language representation.
func FormatGraphQLSDL(models []ModelDefinition) string {
	var b strings.Builder
	b.WriteString("# Synthesized GraphQL Schema Definition Language\n\n")

	for _, m := range models {
		b.WriteString(fmt.Sprintf("type %s {\n", m.Name))
		for fn, ft := range m.Fields {
			gqlType := "String"
			switch ft {
			case "integer":
				gqlType = "Int"
			case "number":
				gqlType = "Float"
			case "boolean":
				gqlType = "Boolean"
			}
			b.WriteString(fmt.Sprintf("  %s: %s\n", fn, gqlType))
		}
		b.WriteString("}\n\n")
	}

	return b.String()
}

// FormatProtobufV3 renders a Proto3 interface definition.
func FormatProtobufV3(packageName string, models []ModelDefinition) string {
	var b strings.Builder
	b.WriteString("syntax = \"proto3\";\n\n")
	if packageName == "" {
		packageName = "lopor.specsynth"
	}
	b.WriteString(fmt.Sprintf("package %s;\n\n", packageName))

	for _, m := range models {
		b.WriteString(fmt.Sprintf("message %s {\n", m.Name))
		fieldIdx := 1
		for fn, ft := range m.Fields {
			protoType := "string"
			switch ft {
			case "integer":
				protoType = "int64"
			case "number":
				protoType = "double"
			case "boolean":
				protoType = "bool"
			}
			b.WriteString(fmt.Sprintf("  %s %s = %d;\n", protoType, fn, fieldIdx))
			fieldIdx++
		}
		b.WriteString("}\n\n")
	}

	return b.String()
}

// FormatTypeScript renders TypeScript interface declarations.
func FormatTypeScript(models []ModelDefinition) string {
	var b strings.Builder
	b.WriteString("// Synthesized TypeScript Interface Definitions\n\n")

	for _, m := range models {
		b.WriteString(fmt.Sprintf("export interface %s {\n", m.Name))
		for fn, ft := range m.Fields {
			tsType := "string"
			switch ft {
			case "integer", "number":
				tsType = "number"
			case "boolean":
				tsType = "boolean"
			case "array":
				tsType = "any[]"
			case "object":
				tsType = "Record<string, any>"
			}
			b.WriteString(fmt.Sprintf("  %s: %s;\n", fn, tsType))
		}
		b.WriteString("}\n\n")
	}

	return b.String()
}

